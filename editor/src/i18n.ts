export function traducir(idioma: "es" | "en", clave: Clave, datos?: Record<string, string | number>): string {
  const plantilla = idioma === "es" ? es[clave] : en[clave];
  return datos ? plantilla.replace(/\{(\w+)\}/g, (_, k: string) => String(datos[k] ?? "")) : plantilla;
}

export function useT(): (clave: Clave, datos?: Record<string, string | number>) => string {
  const idioma = useEstado((e) => e.ajustes.idiomaEfectivo);
  return (clave, datos) => traducir(idioma, clave, datos);
}
